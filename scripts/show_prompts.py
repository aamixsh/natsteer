"""(CPU; run from the repo root.) Every prompt of the loop and the on-policy runner in one Markdown file, for review.

  show_prompts.py [--out data/prompts/all_prompts.md]

1. The templates as stored in natsteer.prompts (edit them there).
2. The round-0 seeds (the writer's examples) with their scenario and system prompt, and the curated ones.
3. Filled prompts from real runs: one writer prompt per behavior (plain and agentic), branch steps, the rewrite, the
   judge; the on-policy scenario prompt, what the assistant sees, the user and tool simulators and the judge.
4. All on-policy scenarios (system prompt, first message, user brief, environment, events) as gpt-6.1-sol wrote them.
The output holds seed and generated text, so it goes to data/ (not in git).
"""

import argparse
import json
from pathlib import Path

from natsteer import prompts as P
from natsteer.convo import load_jsonl
from natsteer.onpolicy import actor_prompt, env_sim_prompt, onpolicy_judge_prompt, scenario_prompt, user_sim_prompt
from natsteer.writer import branch_first_prompt, branch_next_prompt, branch_prefix, judge_prompt, rewrite_prompt, user_turns

ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
ap.add_argument("--out", default="data/prompts/all_prompts.md")
ap.add_argument("--writes", default="data/loop/arms/branch_sol/s2/r0", help="run with plain writes")
ap.add_argument("--agentic", default="data/loop/arms/agentic_sol/s2/r0", help="run with agentic writes")
ap.add_argument("--rewrites", default="data/loop/arms/seeds/r0", help="monitor_v0 run with rewrites")
ap.add_argument("--onpolicy", default="data/onpolicy/pilot")
ap.add_argument("--curated", default="configs/seeds_curated_v3.json")
ap.add_argument("--seeds2", default="data/loop/seeds_r0_v3.jsonl", help="curated seeds (scripts/curate_seeds.py), shown if present")
args = ap.parse_args()

out = []
add = out.append


def block(title, text, level=3):
    add(f"\n{'#' * level} {title}\n\n````text\n{text}\n````\n")


add("# All prompts (generated by scripts/show_prompts.py; edit the templates in src/natsteer/prompts.py)\n")
add("Contents: 1. templates; 2. round-0 seeds; 3. filled prompts from real runs; 4. on-policy scenarios.\n")

# ------------------------------------------------------------------ 1. templates
add("\n## 1. Templates (src/natsteer/prompts.py)\n")
add("\n### Behaviors\n")
for b, t in P.BEHAVIOR_TEXT.items():
    add(f"- **{b}** ({t['name']}): {t['definition']}\n")
block("SCOPE (added to the writer and scenario prompts)", P.SCOPE)
add("\n### Writer settings\n")
add(f"- DEPLOYMENTS ({len(P.DEPLOYMENTS)}): " + "; ".join(P.DEPLOYMENTS) + "\n")
add(f"- TOOL_DEPLOYMENTS ({len(P.TOOL_DEPLOYMENTS)}, agentic prompts): " + "; ".join(P.TOOL_DEPLOYMENTS) + "\n")
add(f"- DOMAINS ({len(P.DOMAINS)}): " + "; ".join(P.DOMAINS) + "\n")
add(f"- TURNS: {P.TURNS} user turns; MAX_EXAMPLE_CHARS per seed: {P.MAX_EXAMPLE_CHARS}\n")
for name in ("WRITER", "TOOLS_RULE", "TOOLS_FORMAT", "BRANCH_FIRST", "BRANCH_ORIGINAL_TOOL_TURN", "BRANCH_NEXT", "BRANCH_TOOLS", "REWRITE",
             "JUDGE", "JUDGE_EVIDENCE", "SCENARIOS", "USER_SIM", "ENV_SIM", "ENV_EVENT", "ENV_DEFAULT", "JUDGE_NOTE", "JUDGE_FORMAT"):
    block(name, getattr(P, name))
    if name == "WRITER":
        for b, r in P.WRITER_RULES.items():
            block(f"WRITER_RULES[{b}] (WRITER {{rules}}; empty for the other behaviors)", r.strip())
        block("SABOTAGE_STAKES (WRITER_RULES[sabotage] {stake} and {stake_example}; one per prompt, chosen from the setting)",
              "\n".join(f"{st}\n    example: {ex}" for st, ex in P.SABOTAGE_STAKES))
        block("LEAK_PATTERNS (writes of these behaviors that match are dropped before the judge)",
              "\n".join(f"{b}: {pat}" for b, pat in P.LEAK_PATTERNS.items()))
    if name == "JUDGE":
        for b, r in P.JUDGE_RULES.items():
            block(f"JUDGE_RULES[{b}] (JUDGE {{rules}}; empty for the other behaviors)", r.strip())
        block("CHECKLIST (second filter for the behaviors in CHECKLIST_ITEMS)", P.CHECKLIST)
        for b, items in P.CHECKLIST_ITEMS.items():
            block(f"CHECKLIST_ITEMS[{b}]", "\n".join(f"{k}: {v}" for k, v in items.items()))

# ------------------------------------------------------------------ 2. seeds
def seed_list(path, behaviors=None):
    for s in load_jsonl(path):
        if behaviors and s["behavior"] not in behaviors:
            continue
        sysm = next((m["content"] for m in s["messages"] if m["role"] == "system"), "")
        meta = s.get("meta", {})
        add(f"\n- **{s['behavior']}** `{s['id']}` ({meta.get('indicator', 'on-policy')}): {meta.get('scenario') or ''}\n"
            f"  - System prompt: {sysm[:600].replace(chr(10), ' ')}{'...' if len(sysm) > 600 else ''}\n")


add("\n## 2. Round-0 seeds (data/loop/seeds_r0.jsonl): the writer's examples, 2 per prompt\n")
seed_list("data/loop/seeds_r0.jsonl")
if Path(args.seeds2).exists():
    cur = json.loads(Path(args.curated).read_text())
    add(f"\n### 2b. New hand-checked seeds ({args.seeds2}; {args.curated}), behaviors {', '.join(cur)}\n")
    for b, spec in cur.items():
        add(f"\n- **{b}:** {spec['note']}\n")
    seed_list(args.seeds2, set(cur))

# ------------------------------------------------------------------ 3. filled prompts
add("\n## 3. Filled prompts from real runs\n")
for label, d in (("plain", args.writes), ("agentic", args.agentic)):
    writes = load_jsonl(Path(d) / "writes.jsonl")
    for b in P.BEHAVIOR_TEXT:
        w = next((w for w in writes if w["behavior"] == b and (label == "plain" or w["setting"].get("tools"))), None)
        if w:
            block(f"Writer, {label}, {b} ({d}, job {w['job']}, setting {w['setting']})", w["prompt"])
for label, d in (("plain", args.writes), ("agentic", args.agentic)):
    orig = {w["job"]: w for w in load_jsonl(Path(d) / "writes.jsonl")}
    br = next(r for r in load_jsonl(Path(d) / "branches.jsonl") if r["status"] == "ok" and r["n_turns"] > r["branch_turn"] + 1
              and (label == "plain" or r.get("tools")))
    w, k = orig[br["job"]], br["branch_turn"]
    block(f"Branch step 0 (aligned replacement of turn {k + 1}), {label}, {br['job']}", branch_first_prompt(w["behavior"], w["messages"], k))
    block(f"Branch step 1 (new user message and aligned reply for turn {k + 2}), {label}, {br['job']}",
          branch_next_prompt(w["behavior"], branch_prefix(br["messages"], k + 1)[:-1], user_turns(w["messages"])[k + 1], bool(br.get("tools"))))
    block(f"Judge (local; the remote judge adds JUDGE_EVIDENCE), {label}, {br['job']}", judge_prompt(w["behavior"], w["messages"]))
rw = next(c for c in load_jsonl(Path(args.rewrites) / "candidates.jsonl") if c["label"] == 1)
block(f"Rewrite (monitor_v0), {rw['id']}", rewrite_prompt(rw["behavior"], rw["messages"]))

op = Path(args.onpolicy)
scen = load_jsonl(op / "scenarios.jsonl")
rolls = load_jsonl(op / "rollouts.jsonl")
block("On-policy scenario prompt to gpt-6.1-sol (one per behavior x pressure; shown: sabotage, incentive)",
      scenario_prompt("sabotage", "incentive", 10, 4, []))


class _Text:  # stands in for the tokenizer so actor_prompt returns its text
    def __call__(self, s, add_special_tokens=False):
        return type("T", (), {"input_ids": s})()


r = next(r for r in rolls if r.get("status") == "ok" and any(m.get("tool") for m in r["messages"]))
s = next(s for s in scen if s["id"] == r["scenario"])
first = r["messages"][: next(i for i, m in enumerate(r["messages"]) if m["role"] == "user") + 1]
block(f"What the assistant (gpt-oss-20b) sees at turn 1, scenario {s['id']} (harmony format, low effort)", actor_prompt(_Text(), first, "low"))
block(f"User simulator, turn 2, scenario {s['id']}", user_sim_prompt(s, r["messages"], 1))
call = next((m for m in r["messages"] if m.get("call")), None)
if call:
    rec, _, a = call["content"].removeprefix("[tool call] ").partition(" ")
    i = r["messages"].index(call)
    block(f"Tool simulator, first call of scenario {s['id']}", env_sim_prompt(s, r["messages"][:i], 0, rec, a))
block(f"On-policy judge (gpt-6.1-sol), rollout {r['id']}", onpolicy_judge_prompt(r["behavior"], r["messages"]))

# ------------------------------------------------------------------ 4. scenarios
add(f"\n## 4. On-policy scenarios ({len(scen)}, {op / 'scenarios.jsonl'})\n")
for s in scen:
    add(f"\n### {s['id']}: {s['deployment']} ({s['domain']})\n\n- **Temptation (not shown to the assistant):** {s['temptation']}\n"
        f"- **First user message:** {s['first_user_message']}\n- **User brief:** {s['user_brief']}\n"
        f"- **Environment:** {s.get('environment') or '(none)'}\n- **Events (turns 2+):** " + " / ".join(s["events"]) + "\n"
        f"\n````text\n{s['system_prompt']}\n````\n")

Path(args.out).parent.mkdir(parents=True, exist_ok=True)
Path(args.out).write_text("".join(out))
print(f"wrote {args.out} ({sum(len(x) for x in out):,} characters)")
